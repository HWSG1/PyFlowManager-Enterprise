    CONVERSATION_ID NVARCHAR(250) NOT NULL,
    COMMUNICATION_ID NVARCHAR(250) NOT NULL,
    TRANSCRIPT_INSTANCE_ID NVARCHAR(250) NOT NULL,
    TRANSCRIPT_ID NVARCHAR(250),
    RECORDING_ID NVARCHAR(250),
    CONVERSATION_START TIMESTAMP,
    CONVERSATION_END TIMESTAMP,
    DURATION_MS BIGINT,
    ORIGINATING_DIRECTION NVARCHAR(50),
    QUEUE_ID NVARCHAR(2100),
    QUEUE_NAME NVARCHAR(2100),
    WRAP_UP_CODE_ID NVARCHAR(2100),
    WRAP_UP_CODE_ID_ULTIMA NVARCHAR(250),
    CONCLUSION_ORIGINAL NVARCHAR(2100),
    CONCLUSION_ULTIMA NVARCHAR(500),
    CONTACT_ID NVARCHAR(250),
    CONTACT_LIST_ID NVARCHAR(250),
    CAMPAIGN_ID NVARCHAR(250),
    COMMUNICATION_PURPOSE NVARCHAR(100),
    TRANSCRIPT_ESTADO NVARCHAR(100),
    TRANSCRIPT_ERROR NVARCHAR(2100),
    MEDIA_TYPE NVARCHAR(100),
    LANGUAGE NVARCHAR(100),
    PROGRAM_ID NVARCHAR(250),
    ENGINE_ID NVARCHAR(250),
    TRANSCRIPT_START_TIME TIMESTAMP,
    TRANSCRIPT_DURATION_MS BIGINT,
    SUBJECT NVARCHAR(2100),
    MESSAGE_TYPE NVARCHAR(100),
    PHRASES_COUNT INTEGER,
    TEXT NCLOB,
    ACOUSTIC_COUNT INTEGER,
    ACOUSTIC_JSON NCLOB,
    FECHA_CARGA TIMESTAMP,
    PRIMARY KEY (CONVERSATION_ID, COMMUNICATION_ID, TRANSCRIPT_INSTANCE_ID)
);


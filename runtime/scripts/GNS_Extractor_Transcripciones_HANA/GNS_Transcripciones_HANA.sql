-- Ejecutar manualmente en SAP HANA; Python no crea ni altera tablas.
-- Dependencias Python: requests, hdbcli, openpyxl, python-dotenv (opcional), tzdata (Windows).
-- HANA: HPR_HOST, HPR_PORT, HPR_USER, HPR_PASSWORD del entorno/globales PyFlow.
-- No se usa HPR_HOST_ESPEJO para escrituras.
-- FECHA_CARGA y timestamps de transcript: America/Tegucigalpa; conversación: GENESYS_TIMEZONE.
-- Claves __STATUS__: reservadas para ausencia/error; __NO_COMMUNICATION__ para ausencia de sesiones.
-- Una grabación con varios transcripts sin ID usa hash de grabación + contenido para desambiguar.
-- Excel >32767 unidades UTF-16: archivo .completo.csv íntegro, marcador en celda Excel.
-- Campaña: enriquecimiento dinámico en .campania.jsonl, sin columnas extra en HANA.
-- Ejecutar una sola carga por conjunto de conversaciones a la vez.


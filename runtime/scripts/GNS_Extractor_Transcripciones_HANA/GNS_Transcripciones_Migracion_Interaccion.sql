WHERE SCHEMA_NAME = 'BI_SS' AND TABLE_NAME LIKE 'GNS_API_TRANSCRIPCIONES%'
ORDER BY TABLE_NAME;

-- PASO 1: renombrar las cinco tablas. Esto conserva datos y permisos en el respaldo.

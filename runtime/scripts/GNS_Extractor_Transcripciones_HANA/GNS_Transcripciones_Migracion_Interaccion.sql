-- PASO 2: crear tablas vacías V2. No ejecutar también el archivo CREATE separado.
-- MODELO V2: una fila principal por CONVERSATION_ID.
-- Detalle hijo conserva claves CONVERSATION_ID + COMMUNICATION_ID + TRANSCRIPT_INSTANCE_ID + secuencia.
-- IDs y metadatos múltiples de la principal: arrays JSON en NCLOB.
-- TRANSCRIPT_DURATION_MS es NULL si hay varios transcripts (no sumar grabaciones solapadas).
-- HPR_HOST/HPR_PORT/HPR_USER/HPR_PASSWORD; Python no ejecuta DDL.
